import os, time, re, subprocess
from datetime import datetime
from pathlib import Path

def get_session_log_status(base_dir: Path) -> list:
    session_file = base_dir / 'scratch' / 'last_session.md'
    status_lines = []
    
    if not session_file.exists():
        status_lines.extend([
            "## ❌ SESSION LOG STATUS: MISSING",
            "- `scratch/last_session.md` was not found. Please invoke `session_handoff` to initialize.",
            ""
        ])
        return status_lines

    last_log_date = None
    try:
        text = session_file.read_text(encoding='utf-8')
        matches = re.findall(r'^## (?:Last )?Session — (\d{4}-\d{2}-\d{2})', text, re.MULTILINE)
        if matches:
            last_log_date = matches[-1]
    except Exception as e:
        status_lines.extend([
            "## ⚠️ SESSION LOG STATUS: READ ERROR",
            f"- Failed to read `{session_file.name}`: {e}",
            ""
        ])
        return status_lines

    if not last_log_date:
        status_lines.extend([
            "## ⚠️ SESSION LOG STATUS: UNPARSED",
            "- No dated session header (`## Session — YYYY-MM-DD`) found in `scratch/last_session.md`.",
            ""
        ])
        return status_lines

    latest_commit_date = None
    try:
        proc = subprocess.run(
            ['git', 'log', '-1', '--format=%as'],
            cwd=base_dir,
            capture_output=True,
            text=True,
            check=True
        )
        latest_commit_date = proc.stdout.strip()
    except Exception as e:
        status_lines.extend([
            "## ℹ️ SESSION LOG STATUS",
            f"- **Last logged session:** {last_log_date}",
            f"- Git commit date unavailable ({e})",
            ""
        ])
        return status_lines

    try:
        d_log = datetime.strptime(last_log_date, "%Y-%m-%d").date()
        d_commit = datetime.strptime(latest_commit_date, "%Y-%m-%d").date()
        gap_days = (d_commit - d_log).days

        if d_log < d_commit:
            status_lines.extend([
                "## ⚠️ SESSION LOG STATUS: STALE",
                f"- **Last logged session:** {last_log_date}",
                f"- **Latest commit:** {latest_commit_date} (stale by {gap_days} day(s))",
                "- **ACTION REQUIRED:** Invoke `session_handoff` before pushing or completing your task.",
                ""
            ])
        else:
            status_lines.extend([
                "## ✅ SESSION LOG STATUS: CURRENT",
                f"- **Last logged session:** {last_log_date}",
                f"- **Latest commit:** {latest_commit_date}",
                ""
            ])
    except Exception as e:
        status_lines.extend([
            "## ℹ️ SESSION LOG STATUS",
            f"- **Last logged session:** {last_log_date}",
            f"- **Latest commit:** {latest_commit_date}",
            f"- Date parse error: {e}",
            ""
        ])

    return status_lines

def get_recent_files(directory, max_files=10, hours_ago=72):
    cutoff_time = time.time() - (hours_ago * 3600)
    recent_files = []
    ignore_dirs = {'.git', '.agents', '.kilo', '.vscode', 'venv', '__pycache__', 'node_modules', 'data'}
    allowed_exts = {'.py', '.json', '.md', '.csv', '.bat', '.ts', '.js'}
    
    try:
        for root, dirs, files in os.walk(directory):
            dirs[:] = [d for d in dirs if d not in ignore_dirs]
            for file in files:
                filepath = Path(root) / file
                if filepath.suffix in allowed_exts:
                    try:
                        mtime = filepath.stat().st_mtime
                        if mtime > cutoff_time:
                            recent_files.append((filepath, mtime))
                    except Exception:
                        pass
    except Exception as e:
        print(f"Error scanning {directory}: {e}")

    recent_files.sort(key=lambda x: x[1], reverse=True)
    return [f[0] for f in recent_files[:max_files]]

def generate_context_file():
    base_dir = Path(__file__).resolve().parent.parent.parent

    content = [
        "# ACTIVE SESSION CONTEXT\n",
        "> **AUTOMATED:** Generated by `generate_context.py`. Do not edit manually.\n",
    ]

    # Inject session log freshness
    content.extend(get_session_log_status(base_dir))

    content.append(f"**Current Working Set ({base_dir.name}):**")

    recent = get_recent_files(base_dir)
    for f in recent:
        content.append(f"- `{base_dir.name}/{f.relative_to(base_dir)}`")
    if not recent:
        content.append("- *(No recently modified files found)*")

    content.extend([
        "\n**Constraints for Today:**",
        "- Do NOT hallucinate variables or schemas. Use Dynamic Schema Discovery.",
        "- Production directories (Streamlit files) are READ-ONLY. Propose changes as code blocks only."
    ])

    context_dir = base_dir / '.agents' / 'rules'
    context_dir.mkdir(parents=True, exist_ok=True)
    
    context_path = context_dir / 'CONTEXT.md'
    context_path.write_text('\n'.join(content), encoding='utf-8')
    print(f"Context generated -> {context_path}")

if __name__ == '__main__':
    generate_context_file()
